function getDataForTable(tables, fieldName) {
  // 遍历表的每一行
  for (const row of tables) {
    // 判断当前行的水位是否为199.5
    if (row[0] === fieldName) {
      // 返回第三列（淹没民房数）
      return row;
    }
  }
  // 若未找到匹配行，返回空数组
  return [];
}

function getStatisticalData(fieldName) {
  if (!fieldName) {
    const overallData = tables.get("整体");
    const result = new Map();
    if (overallData) {
      for (const row of overallData) {
        result.set(row[0], row.slice(1));
      }
    }
    return result;
  }
  return getDataForTable(tables, fieldName);
}

